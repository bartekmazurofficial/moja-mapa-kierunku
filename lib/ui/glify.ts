/**
 * Odcień przypisany kluczowi. Ten sam klucz zawsze dostaje ten sam kolor,
 * więc obszar wygląda tak samo w każdym zestawie i w raporcie.
 *
 * Zakres celowo wąski: 250°–320° to fiolet, indygo i róż. Wyjście poza niego
 * rozbiłoby paletę, a chodzi tylko o to, żeby dwa kafle obok siebie się
 * różniły.
 */
export function odcien(klucz: KluczGlifu): number {
  let suma = 0;
  for (let i = 0; i < klucz.length; i++) suma = (suma * 31 + klucz.charCodeAt(i)) >>> 0;
  return 250 + (suma % 71);
}
